@dataclass(frozen=True)
class Request:
    declaration: pathlib.Path
    candidate_repo: pathlib.Path
    box: pathlib.Path
    box_receipt: pathlib.Path
    profile: pathlib.Path
    base_receipt: pathlib.Path
    readiness_receipt: pathlib.Path
    embedded_vagrantfile: pathlib.Path
    work_dir: pathlib.Path
    evidence_dir: pathlib.Path
    records_dir: pathlib.Path
    plan_out: pathlib.Path
    engine: pathlib.Path
    ssh_port: int | None = None

    @property
    def plan_hash(self) -> pathlib.Path:
        return pathlib.Path(f"{self.plan_out}.sha256")


class Host:
    """The read-only host queries a plan runs, each without a shell and with a timeout."""

    def __init__(self, vboxmanage: str, vagrant: str, git: str) -> None:
        self.vboxmanage = vboxmanage
        self.vagrant = vagrant
        self.git_path = git

    @staticmethod
    def _call(argv: list[str], timeout: float) -> subprocess.CompletedProcess | None:
        environment = dict(os.environ, GIT_TERMINAL_PROMPT="0", GIT_OPTIONAL_LOCKS="0")
        try:
            return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, stdin=subprocess.DEVNULL,
                                  env=environment, check=False)
        except (OSError, subprocess.TimeoutExpired):
            return None

    def _output(self, argv: list[str]) -> str | None:
        result = self._call(argv, QUERY_TIMEOUT)
        return result.stdout if result is not None and result.returncode == 0 else None

    def virtualbox_version(self) -> str | None:
        fields = (self._output([self.vboxmanage, "--version"]) or "").split()
        return fields[0] if len(fields) == 1 else None

    def vagrant_version(self) -> str | None:
        fields = (self._output([self.vagrant, "--version"]) or "").split()
        return fields[1] if len(fields) == 2 and fields[0] == "Vagrant" else None

    def registered(self) -> dict[str, str] | None:
        """The registered VMs as {lowercase UUID: name}, or None when VirtualBox cannot list them."""
        output = self._output([self.vboxmanage, "list", "vms"])
        if output is None:
            return None
        vms: dict[str, str] = {}
        for line in output.splitlines():
            quoted, _, braced = line.rpartition(" {")
            uuid = braced[:-1]
            if braced.endswith("}") and UUID_PATTERN.fullmatch(uuid) and len(quoted) >= 2 \
                    and quoted[0] == quoted[-1] == '"':
                vms[uuid.lower()] = quoted[1:-1]
        return vms

    def machine_folder(self) -> pathlib.Path | None:
        for line in (self._output([self.vboxmanage, "list", "systemproperties"]) or "").splitlines():
            key, _, value = line.partition(":")
            if key.strip() == "Default machine folder" and os.path.isabs(value.strip()):
                return pathlib.Path(value.strip())
        return None

    def git(self, repository: pathlib.Path, *arguments: str) -> subprocess.CompletedProcess | None:
        return self._call([self.git_path, "--literal-pathspecs", "-C", str(repository), *arguments], GIT_TIMEOUT)


def check_request(request: Request) -> None:
    """Usage checks that stop before any query or plan is written; every other failure is a refusal."""
    for name, value in vars(request).items():
        if isinstance(value, pathlib.Path) and not value.is_absolute():
            raise LaneBoxError(f"--{name.replace('_', '-')} must be an absolute path")
    for path in (request.work_dir, request.evidence_dir, request.records_dir, request.plan_out.parent):
        require_private_directory(path)
    if os.path.lexists(request.plan_out) or os.path.lexists(request.plan_hash):
        raise LaneBoxError(f"plan output already exists: {request.plan_out}")
    if request.ssh_port is not None and request.ssh_port not in PORT_RANGE:
        raise LaneBoxError("--ssh-port must be from 1024 to 65535")


def extracted_bytes(box: pathlib.Path) -> int:
    """The bytes the box's regular members take once Vagrant extracts it."""
    with tarfile.open(box, "r:*") as archive:
        return sum(member.size for member in archive if member.isfile())


def contract_of(toolchain: Iterable[dict]) -> dict[str, object]:
    """The REQ-091 contract part of a toolchain block: each tool's probe, by name."""
    return {entry.get("name"): entry.get("probe") for entry in toolchain}


def check_box(request: Request, declaration: Declaration | None) -> tuple[dict, dict | None, list[Refusal]]:
    """Check the box digest first (TEST-103), then the whole receipt, then the declared toolchain contract.

    Return the plan's box block, the receipt's hardware once the receipt verifies, and the refusals.
    """
    box: dict = {"path": str(request.box), "sha256": None, "receiptSha256": None, "extractedBytes": None,
                 "profile": None, "sshHostKey": None}
    try:
        receipt = load_json(request.box_receipt, "lane box receipt")
        box["receiptSha256"] = sha256_file(request.box_receipt)
        box["sha256"] = sha256_file(request.box)
    except (OSError, LaneBoxError) as error:
        return box, None, [Refusal("box-receipt", str(error))]
    recorded = receipt.get("box") if isinstance(receipt.get("box"), dict) else {}
    if recorded.get("sha256") != box["sha256"]:
        return box, None, [Refusal("box-digest", f"the box's SHA-256 {box['sha256']} differs from the "
                                                 f"{recorded.get('sha256')!r} its receipt records")]
    try:
        verify_box_receipt(request.box_receipt, box=request.box, profile_path=request.profile,
                           base_receipt=request.base_receipt, readiness_receipt=request.readiness_receipt,
                           embedded_vagrantfile=request.embedded_vagrantfile)
        box["extractedBytes"] = extracted_bytes(request.box)
    except (OSError, tarfile.TarError, LaneBoxError) as error:
        return box, None, [Refusal("box-receipt", str(error))]
    box["profile"], box["sshHostKey"] = receipt["profile"], receipt["sshHostKey"]
    if declaration is None:
        return box, receipt["virtualBox"], []
    declared = contract_of(declaration.toolchain)
    received = contract_of(receipt["toolchain"])
    differing = sorted(name for name in set(declared) | set(received) if declared.get(name) != received.get(name))
    if differing:
        return box, receipt["virtualBox"], [Refusal(
            "toolchain-contract", f"the declared toolchain differs from the box receipt's for {', '.join(differing)}")]
    return box, receipt["virtualBox"], []


def _tree_entries(host: Host, repository: pathlib.Path, commit: str, paths: list[str]) -> dict[str, str] | None:
    """{path: mode} for every listed path and each of its parent directories in ``commit``.

    One depth per ``ls-tree`` call: ls-tree omits a directory it descends through to reach a deeper
    pathspec, so a call never names a path together with its ancestor. A level is listed only below
    parents already seen to be directories."""
    prefixes = {"/".join(path.split("/")[:end]) for path in paths for end in range(1, path.count("/") + 2)}
    entries: dict[str, str] = {}
    depth = 0
    while level := sorted(prefix for prefix in prefixes if prefix.count("/") == depth
                          and (depth == 0 or entries.get(prefix.rpartition("/")[0]) == "040000")):
        result = host.git(repository, "ls-tree", "-z", commit, "--", *level)
        if result is None or result.returncode != 0:
            return None
        for record in filter(None, result.stdout.split("\0")):
            meta, _, path = record.partition("\t")
            entries[path] = meta.split(" ", 1)[0]
        depth += 1
    return entries


def _path_problem(path: str, entries: Mapping[str, str], directory: bool) -> str | None:
    parts = path.split("/")
    for end in range(1, len(parts) + 1):
        prefix = "/".join(parts[:end])
        mode = entries.get(prefix)
        if mode is None:
            return f"{prefix!r} is not in the candidate commit"
        if mode == "120000":
            return f"{prefix!r} is a symbolic link"
        if mode == "160000":
            return f"{prefix!r} is a submodule, which a git bundle of the commit does not carry"
        if (end < len(parts) or directory) and mode != "040000":
            return f"{prefix!r} is not a directory"
    return None


def check_candidate(host: Host, repository: pathlib.Path, declaration: Declaration) -> list[Refusal]:
    """The clone's top level holds the commit, and every input and the working directory are in its tree."""
    # git reads pathspecs below the directory it runs in, so a subdirectory would check the wrong paths.
    prefix = host.git(repository, "rev-parse", "--show-prefix")
    if prefix is None or prefix.returncode != 0 or prefix.stdout.strip():
        return [Refusal("candidate-missing", f"{repository} is not the top level of a git clone")]
    # cat-file -t names the object itself; a tag would otherwise be followed to its commit.
    found = host.git(repository, "cat-file", "-t", declaration.commit)
    if found is None or found.returncode != 0 or found.stdout.strip() != "commit":
        return [Refusal("candidate-missing", f"{declaration.commit} is not a commit object in {repository}")]
    paths = [(path, False) for path in declaration.inputs]
    if declaration.working_directory != ".":
        paths.append((declaration.working_directory, True))
    if not paths:
        return []
    entries = _tree_entries(host, repository, declaration.commit, [path for path, _ in paths])
    if entries is None:
        return [Refusal("candidate-path", f"cannot list the tree of commit {declaration.commit}")]
    refusals = []
    for path, directory in paths:
        problem = _path_problem(path, entries, directory)
        if problem:
            what = "workingDirectory" if directory else "input"
            refusals.append(Refusal("candidate-path", f"{what} {path!r}: {problem}"))
    return refusals


def check_secrets(declaration: Declaration, environ: Mapping[str, str]) -> list[Refusal]:
    """REQ-093: each declared name has a non-empty value in the dispatching context. Values go nowhere."""
    return [Refusal("secret-missing", f"declared secret {name} is missing or empty in the dispatching context")
            for name in declaration.secrets if not environ.get(name)]


def engine_commit(host: Host, engine: pathlib.Path) -> tuple[str | None, list[Refusal]]:
    """The engine's commit, refused unless the checkout's tracked files match it."""
    head = host.git(engine, "rev-parse", "--verify", "HEAD^{commit}")
    commit = head.stdout.strip() if head is not None and head.returncode == 0 else ""
    if len(commit) != 40:
        return None, [Refusal("engine-commit", f"cannot read the engine commit in {engine}")]
    status = host.git(engine, "status", "--porcelain", "--untracked-files=no")
    if status is None or status.returncode != 0 or status.stdout.strip():
        return commit, [Refusal("engine-commit", "the engine checkout has changes, so its commit does not "
                                                 "identify the code that would run")]
    return commit, []


@dataclass
class Records:
    """What the earlier lane teardown receipts in the records directory observed."""

    outcomes: dict[str, set[str]]
    names: set[str]


def earlier_records(records_dir: pathlib.Path) -> tuple[Records, list[Refusal]]:
    records = Records(outcomes={}, names=set())
    refusals: list[Refusal] = []
    for path in sorted(records_dir.glob(f"*{RECORD_SUFFIX}")):
        try:
            receipt = verify_receipt(path)
        except LaneBoxError as error:
            refusals.append(Refusal("earlier-record-invalid", f"{path.name}: {error}"))
            continue
        records.outcomes.setdefault(receipt["instance"]["uuid"], set()).add(receipt["outcome"])
        if receipt["instance"]["name"] is not None:
            records.names.add(receipt["instance"]["name"])
    return records, refusals


def reused_uuids(registered: Iterable[str], records: Records) -> list[str]:
    """REQ-101: UUIDs VirtualBox lists although an earlier lane record observed them removed or absent."""
    return sorted(uuid for uuid in registered if records.outcomes.get(uuid, set()) & set(REMOVAL_OUTCOMES))


def port_is_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        try:
            probe.bind(("127.0.0.1", port))
        except OSError:
            return False
    return True


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


def _existing(path: pathlib.Path) -> pathlib.Path:
    while not path.exists():
        path = path.parent
    return path


def check_disk(needs: list[tuple[pathlib.Path, int]]) -> tuple[list[dict], list[Refusal]]:
    """Add up the bytes each file system must hold, and compare each total with its free space."""
    totals: dict[int, list] = {}
    for path, amount in needs:
        path = _existing(path)
        totals.setdefault(path.stat().st_dev, [path, 0])[1] += amount
    disks, refusals = [], []
    for path, amount in totals.values():
        free = shutil.disk_usage(path).free
        disks.append({"path": str(path), "requiredBytes": amount, "freeBytes": free})
        if free < amount:
            refusals.append(Refusal("host-disk-space", f"{path} has {free} bytes free; one lane instance needs {amount}"))
    return disks, refusals


def output_disk(run_dir: pathlib.Path, max_output_bytes: int) -> dict:
    """REQ-106: a fixed-size disk that holds at most ``maxOutputBytes``, in whole MiB."""
    return {"path": str(run_dir / OUTPUT_DISK_NAME), "sizeMb": math.ceil(max_output_bytes / MIB), "format": "VDI",
            "variant": "Fixed", "controller": OUTPUT_DISK_CONTROLLER, "port": OUTPUT_DISK_PORT, "device": 0}


def ruby_string(value: str) -> str:
    """A Ruby single-quoted literal; a control character is refused rather than escaped."""
    if any(unicodedata.category(character) == "Cc" for character in value):
        raise LaneBoxError("refusing to render a Vagrantfile path that holds a control character")
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render_vagrantfile(name: str, port: int, hardware: Mapping[str, object], disk: Mapping[str, object]) -> str:
    if not INSTANCE_NAME.fullmatch(name) or port not in PORT_RANGE:
        raise LaneBoxError("refusing to render a Vagrantfile for an invalid instance name or port")
    values = [hardware.get(key) for key in ("memoryMb", "cpus", "vramMb")]
    if not all(type(value) is int and value > 0 for value in values):
        raise LaneBoxError("refusing to render a Vagrantfile with invalid hardware")
    if type(disk.get("sizeMb")) is not int or disk["sizeMb"] <= 0 or not isinstance(disk.get("path"), str):
        raise LaneBoxError("refusing to render a Vagrantfile with an invalid output disk")
    memory, cpus, vram = values
    return VAGRANTFILE.format(name=name, port=port, guest_port=SSH_GUEST_PORT, memory=memory, cpus=cpus, vram=vram,
                              disk=ruby_string(disk["path"]), disk_mb=disk["sizeMb"],
                              controller=OUTPUT_DISK_CONTROLLER, disk_port=OUTPUT_DISK_PORT)


def _step(name: str, phase: str, runs: str, argv: list[str] | None, timeout: int | None, *,
          secrets: Iterable[str] = (), cwd: str | None = None, environment: Mapping[str, str] | None = None) -> dict:
    return {"name": name, "phase": phase, "runs": runs, "argv": argv, "cwd": cwd,
            "environment": dict(environment or {}), "secrets": list(secrets), "timeoutSeconds": timeout}


def plan_steps(request: Request, host: Host, declaration: Declaration, name: str, box_sha256: str) -> list[dict]:
    """The ordered steps of a run (#166 design, section 4). Secret names appear; values never do.

    ``engine`` steps are done by the lane executor itself and have no argv. A phase's guest steps run
    in order in one unit that the guest stops after the phase's declared timeout, which the plan keeps in
    ``guestUnits``; the guest steps themselves have no timeout. The build unit starts first and
    waits for carrier loss, because SSH runs over the adapter whose link goes off; the link never comes
    back, so the guest writes its outputs to the output disk and powers itself off (REQ-106, C1).
    """
    run_dir = request.work_dir / name
    vagrant_environment = {"VAGRANT_HOME": str(run_dir / "vagrant-home"), "TMPDIR": str(run_dir / "tmp")}
    show = [host.vboxmanage, "showvminfo", UUID_PLACEHOLDER, "--machinereadable"]
    return [
        _step("box-add", "prepare", "host", [
            host.vagrant, "box", "add", "--name", name, "--provider", "virtualbox", "--checksum", box_sha256,
            "--checksum-type", "sha256", str(request.box),
        ], BOX_ADD_TIMEOUT, cwd=str(run_dir), environment=vagrant_environment),
        _step("up", "prepare", "host", [host.vagrant, "up", "--provider", "virtualbox"], UP_TIMEOUT,
              cwd=str(run_dir), environment=vagrant_environment),
        _step("verify-instance", "prepare", "host", show, QUERY_TIMEOUT),
        _step("connect", "prepare", "engine", None, None),
        _step("check-runner-units", "prepare", "engine", None, None),
        *(_step(f"probe-{tool['name']}", "prepare", "guest", list(tool["probe"]["argv"]), PROBE_TIMEOUT)
          for tool in declaration.toolchain),
        _step("transfer-candidate", "prepare", "engine", None, None),
        *(_step(f"fetch-{index}", "fetch", "guest", list(argv), None, cwd=declaration.working_directory)
          for index, argv in enumerate(declaration.fetch.steps, start=1)),
        *([_step("await-fetch", "fetch", "engine", None, declaration.fetch.timeout + HOST_DEADLINE_GRACE)]
          if declaration.fetch.steps else []),
        *(_step(f"build-{index}", "build", "guest", list(argv), None, secrets=declaration.secrets,
                cwd=declaration.working_directory)
          for index, argv in enumerate(declaration.build.steps, start=1)),
        _step("network-off", "build", "host", [host.vboxmanage, "controlvm", UUID_PLACEHOLDER, "setlinkstate1", "off"],
              QUERY_TIMEOUT),
        _step("verify-network-off", "build", "host", show, QUERY_TIMEOUT),
        _step("await-poweroff", "build", "engine", None, declaration.build.timeout + HOST_DEADLINE_GRACE),
        _step("read-outputs", "collect", "engine", None, None),
        _step("write-evidence", "collect", "engine", None, None),
        _step("teardown", "teardown", "host", [
            sys.executable, str(request.engine / "scripts" / "Invoke-Lane.py"), "teardown", "--uuid", UUID_PLACEHOLDER,
            "--run-dir", str(run_dir), "--box", str(request.box), "--box-sha256", box_sha256,
            "--receipt-out", str(request.records_dir / f"{name}{RECORD_SUFFIX}"), "--run",
        ], None),
    ]


def check_host(request: Request, host: Host, name: str, records: Records, box: dict,
               hardware: Mapping[str, int] | None, disk: Mapping[str, int] | None,
               max_output_bytes: int | None) -> tuple[dict, int, list[Refusal]]:
    """VirtualBox, Vagrant, the instance name, the SSH port, and the disk space one instance needs."""
    refusals: list[Refusal] = []
    details: dict = {"virtualBox": host.virtualbox_version(), "vagrant": host.vagrant_version(),
                     "machineFolder": None, "disks": []}
    if details["virtualBox"] is None:
        refusals.append(Refusal("host-virtualbox", "VBoxManage --version failed or printed an unexpected form"))
    if details["vagrant"] is None:
        refusals.append(Refusal("host-vagrant", "vagrant --version failed or printed an unexpected form"))
    registered = host.registered()
    if registered is None:
        refusals.append(Refusal("host-virtualbox", "VBoxManage list vms failed"))
        registered = {}
    refusals += [Refusal("reused-instance-uuid", f"VirtualBox lists {uuid}, which an earlier lane record "
                                                 "observed removed or absent") for uuid in reused_uuids(registered, records)]
    taken = [what for what, used in (
        ("a registered VM", name in registered.values()),
        ("the run directory", os.path.lexists(request.work_dir / name)),
        ("the evidence directory", os.path.lexists(request.evidence_dir / name)),
        ("a lane record", name in records.names or os.path.lexists(request.records_dir / f"{name}{RECORD_SUFFIX}")),
    ) if used]
    if taken:
        refusals.append(Refusal("instance-name-in-use", f"{name} is already used by {', '.join(taken)}"))
    port = request.ssh_port if request.ssh_port is not None else free_port()
    if not port_is_free(port):
        refusals.append(Refusal("ssh-port", f"127.0.0.1:{port} is in use"))
    folder = host.machine_folder()
    if folder is None:
        refusals.append(Refusal("host-virtualbox", "VBoxManage list systemproperties named no default machine folder"))
    else:
        details["machineFolder"] = str(folder)
    if folder is not None and hardware is not None:
        # Vagrant copies the box under VAGRANT_HOME and extracts it there; VirtualBox imports the disk
        # into its machine folder, and a dynamic disk never grows past its capacity. The fixed output disk
        # sits in the run directory, and the outputs read from it are copied into the evidence directory.
        needs = [(request.work_dir, request.box.stat().st_size + box["extractedBytes"]),
                 (folder, hardware["diskGb"] * GIB)]
        if disk is not None and max_output_bytes is not None:
            needs += [(request.work_dir, disk["sizeMb"] * MIB), (request.evidence_dir, max_output_bytes)]
        details["disks"], found = check_disk(needs)
        refusals += found
    return details, port, refusals


def make_plan(request: Request, host: Host, environ: Mapping[str, str]) -> dict:
    """Check every input and return the plan; its outcome is ``ready`` only when nothing was refused."""
    name = new_instance_name()
    declaration, declaration_sha256, refusals = load_declaration(request.declaration)
    box, hardware, found = check_box(request, declaration)
    refusals += found
    if declaration is not None:
        refusals += check_candidate(host, request.candidate_repo, declaration)
        refusals += check_secrets(declaration, environ)
    engine, found = engine_commit(host, request.engine)
    refusals += found
    records, found = earlier_records(request.records_dir)
    refusals += found
    disk = None if declaration is None else output_disk(request.work_dir / name, declaration.max_output_bytes)
    details, port, found = check_host(request, host, name, records, box, hardware, disk,
                                      None if declaration is None else declaration.max_output_bytes)
    refusals += found
    vagrantfile = None if hardware is None or disk is None else render_vagrantfile(name, port, hardware, disk)
    ready = declaration is not None and hardware is not None
    return {
        "schema": PLAN_SCHEMA,
        "engine": {"path": str(request.engine), "commit": engine},
        "instance": {"name": name, "runDirectory": str(request.work_dir / name),
                     "evidenceDirectory": str(request.evidence_dir / name)},
        "declaration": {"path": str(request.declaration), "sha256": declaration_sha256},
        "candidate": {"repository": str(request.candidate_repo),
                      "commit": None if declaration is None else declaration.commit},
        "box": box,
        "host": details,
        "hardware": hardware,
        "network": {"adapter": 1, "mode": "nat", "localhostReachable": False, "linkOffFrom": LINK_OFF_FROM,
                    "linkRestored": False,
                    "sshForward": {"hostIp": "127.0.0.1", "hostPort": port, "guestPort": SSH_GUEST_PORT,
                                   "autoCorrect": False}},
        "outputDisk": disk,
        "vagrantfile": None if vagrantfile is None else {
            "text": vagrantfile, "sha256": hashlib.sha256(vagrantfile.encode("utf-8")).hexdigest()},
        "guestUnits": None if declaration is None else {
            phase: {"timeoutSeconds": getattr(declaration, phase).timeout} for phase in GUEST_PHASES},
        "steps": plan_steps(request, host, declaration, name, box["sha256"]) if ready else [],
        "earlierInstances": sorted(records.outcomes),
        "refusals": [refusal._asdict() for refusal in refusals],
        "outcome": "refused" if refusals else "ready",
    }


def write_plan(request: Request, value: dict) -> None:
    try:
        write_new_with_digest(request.plan_out, request.plan_hash, json.dumps(value, indent=2, sort_keys=True) + "\n")
    except OSError as error:
        raise LaneBoxError(f"cannot write the plan: {error}") from error
